class RegresionStrategy:
      def fit(self, X, y):
        pass

      def predict(self, X):
        pass

      def describir(self):
        pass

class RegresionLinealSimpleStrategy(RegresionStrategy):
    def __init__(self):
        self.modelo = LinearRegression()

    def fit(self, X, y):
        self.modelo.fit(X, y)

    def predict(self, X):
        return self.modelo.predict(X)

    def describir(self):
        print(self.modelo)

class RegresionLinealMultipleStrategy(RegresionStrategy):
    def __init__(self):
        self.modelo = LinearRegression()

    def fit(self, X, y):
        self.modelo.fit(X, y)

    def predict(self, X):
        return self.modelo.predict(X)

    def describir(self):
        print("Modelo de Regresión Lineal Múltiple")
        print(self.modelo)

class EstrategiaRegresionFactory:
    @staticmethod
    def crear(X):
        # Si X es un DataFrame o NumPy array, verificamos la cantidad de columnas
        if hasattr(X, 'shape'):
            # Si tiene 1 sola columna o es de una dimensión
            if len(X.shape) == 1 or X.shape[1] == 1:
                return RegresionLinealSimpleStrategy()
            else:
                return RegresionLinealMultipleStrategy()
        else:
            # Por defecto si no tiene shape (por ejemplo, una lista simple de un feature)
            return RegresionLinealSimpleStrategy()

