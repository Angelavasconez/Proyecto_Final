class FlujoRegresionFacade:
    def __init__(self):
        self.limpiador = LimpiadorDatos()

    def ejecutar(self, df, columnas_X, columna_y):
        # 1. Limpieza de datos básica utilizando el Limpiador de Datos
        df_limpio = self.limpiador.limpiar(df)
        print("--- Limpieza de datos realizada con éxito ---")

        # 2. Separación de variables predictoras (X) e independiente (y)
        X = df_limpio[columnas_X]
        y = df_limpio[columna_y]

        # 3. Creación de la estrategia de regresión dinámica usando la Fábrica
        estrategia = EstrategiaRegresionFactory.crear(X)

        # 4. Ajustar/Entrenar el modelo
        estrategia.fit(X, y)

        # 5. Describir la estrategia seleccionada y retornar predicciones junto con el modelo
        print("--- Flujo Ejecutado con Éxito ---")
        estrategia.describir()
        predicciones = estrategia.predict(X)

        return estrategia, predicciones

