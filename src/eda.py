class GestorDataset:
  """
  Clase que recibe la ruta, carga el csv y mantiene encapsulado el dataset.
  """
  def __init__(self, RUTA_DATASET):
        self.ruta = RUTA_DATASET
        self._data = None # El atributo encapsulado (oculto)

  def cargar_datos(self):
    """Valida y lee el archivo CSV."""
    if not os.path.exists(self.ruta):
      raise FileNotFoundError(f"El archivo {self.ruta} no existe.")
    try:
      self.data = pd.read_csv(self.ruta)
      print(f"El archivo {self.ruta} se cargó correctamente.")
    except Exception as e:
      raise ValueError(f"Error al leer el archivo {self.ruta}: {e}")

  def obtener_datos(self):
    """Devuelve el dataset."""
    if self.data is None:
      raise ValueError("El dataset no ha sido cargado.")
    return self.data.copy()

  def mostrar_dimensiones(self):
    """Devuelve filas y columnas del dataset."""
    df = self.obtener_datos()
    return df.shape

  def listar_variables(self):
    """Devuelve los nombres de las columnas."""
    df = self.obtener_datos()
    return df.columns.tolist()

  def describir_dataset(self):
    """Devuelve un resumen con variables numéricas/categóricas, nulos y duplicados."""
    df = self.obtener_datos()
    num_vars = df.select_dtypes(include=[np.number]).shape[1]
    cat_vars = df.select_dtypes(exclude=[np.number]).shape[1]
    nulos = df.isnull().sum().sum()
    duplicados = df.duplicated().sum()
    return {"Variables numéricas": num_vars,
            "Variables categóricas": cat_vars,
            "Nulos": nulos, "Registros Duplicados": duplicados}

