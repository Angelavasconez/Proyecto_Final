class AnalizadorVariable(ABC):
  """
  Clase abstracta que recibe un nombre de variable y una serie de datos.
  """
  def __init__(self, nombre_variable, serie_datos):
    self.nombre_variable = nombre_variable
    self.serie_datos = serie_datos

  @abstractmethod
  def analizar(self):
    """Método abstracto que debe ser implementado por las clases hijas."""
    pass

class AnalizadorNumerico(AnalizadorVariable):
  """
  Analizador especializado para variables numéricas que retorna medidas estadísticas descriptivas e IQR
  """
  def analizar(self):
    # Usamos self.serie_datos que es el atributo heredado
    d = self.serie_datos.dropna() # Quitamos los datos vacíos para no tener errores
    q1 = d.quantile(0.25)
    q3 = d.quantile(0.75)

    # Retorna un diccionario con puros cálculos matemáticos
    return {
        "Variable": self.nombre_variable,
        "Tipo": "Numérico",
        "Registros": len(d),
        "Nulos": self.serie_datos.isnull().sum(),
        "Media": d.mean(),
        "Mediana": d.median(),
        "Desviación Estándar": d.std(),
        "Mínimo": d.min(),
        "Máximo": d.max(),
        "Q1": q1,
        "Q3": q3,
        "IQR": q3 - q1
    }

class AnalizadorCategorico(AnalizadorVariable):
  """
  Analizador especializado para variables categóricas que retorna categorías,
  moda, frecuencia y porcentaje de la categoría dominante
  """
  def analizar(self):
    # Usamos self.serie_datos que es el atributo heredado
    d = self.serie_datos.dropna()
    moda = d.mode().iloc[0] if not d.empty else None
    frecuencia = d.value_counts().iloc[0] if not d.empty else 0
    porcentaje = (frecuencia / len(d)) * 100 if len(d) > 0 else 0

    #Retorna un diccionario con conteos de texto
    return {
        "Variable": self.nombre_variable,
        "Tipo": "Categórica",
        "Registros": len(self.serie_datos),
        "Nulos": self.serie_datos.isnull().sum(),
        "Categorías Únicas": d.nunique(),
        "Moda": moda,
        "Frecuencia": frecuencia,
        "Porcentaje Dominante": f"{porcentaje:.2f}%"
    }

